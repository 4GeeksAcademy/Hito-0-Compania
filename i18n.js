const DEFAULT_LANG = "es";
const SUPPORTED_LANGS = ["es", "en"];
const STORAGE_KEY = "trackflow_lang";

function getPreferredLanguage() {
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored && SUPPORTED_LANGS.includes(stored)) {
    return stored;
  }

  const browserLang = (navigator.language || "").slice(0, 2).toLowerCase();
  if (SUPPORTED_LANGS.includes(browserLang)) {
    return browserLang;
  }

  return DEFAULT_LANG;
}

function setSwitchButtonStyles(activeLang) {
  const buttons = document.querySelectorAll("[data-lang-switch]");
  buttons.forEach((button) => {
    const isActive = button.getAttribute("data-lang-switch") === activeLang;
    button.classList.toggle("bg-brand-600", isActive);
    button.classList.toggle("text-white", isActive);
    button.classList.toggle("text-ink-700", !isActive);
  });
}

function applyTranslations(lang) {
  const page = document.body.getAttribute("data-page");
  const pageTranslations = TRANSLATIONS[page];
  if (!pageTranslations) return;

  const selectedLanguage = pageTranslations[lang] ? lang : DEFAULT_LANG;
  const values = pageTranslations[selectedLanguage];

  document.documentElement.lang = selectedLanguage;
  if (values.title) {
    document.title = values.title;
  }

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.getAttribute("data-i18n");
    if (!key || values[key] === undefined) return;

    const hasHtml = values[key].includes("<span");
    if (hasHtml) {
      element.innerHTML = values[key];
    } else {
      element.textContent = values[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.getAttribute("data-i18n-placeholder");
    if (!key || values[key] === undefined) return;
    element.setAttribute("placeholder", values[key]);
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const key = element.getAttribute("data-i18n-aria-label");
    if (!key || values[key] === undefined) return;
    element.setAttribute("aria-label", values[key]);
  });

  localStorage.setItem(STORAGE_KEY, selectedLanguage);
  setSwitchButtonStyles(selectedLanguage);
}

document.querySelectorAll("[data-lang-switch]").forEach((button) => {
  button.addEventListener("click", () => {
    const lang = button.getAttribute("data-lang-switch");
    if (!lang) return;
    applyTranslations(lang);
  });
});

applyTranslations(getPreferredLanguage());
